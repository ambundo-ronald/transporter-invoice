import frappe
from frappe import _


def set_if_has_field(doc, fieldname, value):
	if doc.meta.has_field(fieldname):
		doc.set(fieldname, value)


def get_delivery_invoice_status(sales_invoice=None, purchase_invoice=None):
	if sales_invoice and purchase_invoice:
		return "Fully Invoiced"
	if sales_invoice:
		return "Customer Invoiced"
	if purchase_invoice:
		return "Transporter Invoiced"
	return "Ready for Invoicing"


def sync_delivery_invoice_status(delivery_name):
	links = frappe.db.get_value(
		"Transport Delivery",
		delivery_name,
		["sales_invoice", "purchase_invoice"],
		as_dict=True,
	)
	if not links:
		return

	sales_invoice = _get_active_invoice("Sales Invoice", links.sales_invoice)
	purchase_invoice = _get_active_invoice("Purchase Invoice", links.purchase_invoice)
	link_updates = {}
	if links.sales_invoice and not sales_invoice:
		link_updates["sales_invoice"] = None
	if links.purchase_invoice and not purchase_invoice:
		link_updates["purchase_invoice"] = None
	if link_updates:
		frappe.db.set_value("Transport Delivery", delivery_name, link_updates, update_modified=False)

	frappe.db.set_value(
		"Transport Delivery",
		delivery_name,
		"workflow_state",
		get_delivery_invoice_status(sales_invoice, purchase_invoice),
		update_modified=False,
	)


def _get_active_invoice(doctype, invoice_name):
	if not invoice_name:
		return None
	docstatus = frappe.db.get_value(doctype, invoice_name, "docstatus")
	return invoice_name if docstatus is not None and int(docstatus) != 2 else None


def unlink_transport_invoice(doc, method=None):
	link_field = "sales_invoice" if doc.doctype == "Sales Invoice" else "purchase_invoice"
	delivery_names = frappe.get_all(
		"Transport Delivery",
		filters={link_field: doc.name},
		pluck="name",
	)

	for delivery_name in delivery_names:
		frappe.db.set_value(
			"Transport Delivery",
			delivery_name,
			link_field,
			None,
			update_modified=False,
		)
		sync_delivery_invoice_status(delivery_name)

	if doc.doctype == "Sales Invoice":
		frappe.db.set_value(
			"Transport Billing Batch",
			{"sales_invoice": doc.name},
			"sales_invoice",
			None,
			update_modified=False,
		)
	else:
		frappe.db.set_value(
			"Transporter Billing Batch",
			{"purchase_invoice": doc.name},
			"purchase_invoice",
			None,
			update_modified=False,
		)


@frappe.whitelist()
def cancel_transport_invoice_only(doctype, invoice_name):
	if doctype not in {"Sales Invoice", "Purchase Invoice"}:
		frappe.throw(_("Only transport Sales Invoices and Purchase Invoices can use this action."))

	frappe.db.sql(
		f"select name from `tab{doctype}` where name = %s for update",
		invoice_name,
	)
	invoice = frappe.get_doc(doctype, invoice_name)
	invoice.check_permission("cancel")
	if invoice.docstatus != 1:
		frappe.throw(_("Only a submitted invoice can be cancelled."))
	if not _is_transport_invoice(invoice):
		frappe.throw(_("Invoice {0} was not generated by Transport Invoicing.").format(frappe.bold(invoice.name)))

	# Remove inbound links before Frappe performs its submitted-document link check.
	unlink_transport_invoice(invoice)
	invoice.cancel()
	return invoice.name


def _is_transport_invoice(invoice):
	for fieldname in (
		"custom_transport_delivery",
		"custom_transport_billing_batch",
		"custom_transporter_billing_batch",
	):
		if invoice.meta.has_field(fieldname) and invoice.get(fieldname):
			return True

	return any(row.get("custom_transport_delivery") for row in invoice.get("items") or [])
